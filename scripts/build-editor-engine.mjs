/**
 * Bundle the editor engine.
 *
 * `editor-engine/engine.js` is source; `lib/client/client.editor-engine.js` is
 * the one file the panel loads. The output is committed on purpose: this plugin
 * ships without a build step and `files` contains only `lib/`, so a published
 * package must already contain the bundle. `--check` rebuilds in memory and
 * fails when the committed file no longer matches the source, which is the only
 * way a generated artifact and its input stay honest with each other.
 */
import { readFile, stat } from 'node:fs/promises'
import { build } from 'esbuild'

const output = 'lib/client/client.editor-engine.js'

const options = {
  entryPoints: ['editor-engine/engine.js'],
  bundle: true,
  format: 'iife',
  globalName: '__sshwsp_engine',
  platform: 'browser',
  target: ['chrome110', 'safari16'],
  minify: true,
  legalComments: 'none',
  banner: {
    js: '/* Generated by scripts/build-editor-engine.mjs from editor-engine/engine.js — do not edit. */',
  },
  // The Host evaluates every chunk as `window.__ModuleLoader__.load({...})` and
  // hands `require.async` the factory's return value, so the bundle has to
  // register itself the same way a hand-written chunk does. The explicit
  // `window` assignment before the registration is not redundant: whether the
  // Host runs a chunk as a classic script (top-level `var` becomes a window
  // property) or through `new Function` (it does not) is not ours to rely on.
  footer: {
    js: [
      'window.__sshwsp_engine = __sshwsp_engine;',
      'window.__ModuleLoader__.load({',
      "  id: '@shiqyka/dsh-ssh-workspace',",
      "  chunk: 'client.editor-engine.js',",
      '  factory: () => window.__sshwsp_engine,',
      '});',
      '',
    ].join('\n'),
  },
}

const check = process.argv.includes('--check')

if (check) {
  const result = await build({ ...options, write: false, outfile: undefined })
  const fresh = result.outputFiles[0].text
  const committed = await readFile(output, 'utf8')
  if (fresh !== committed) {
    console.error(`${output} is stale: run \`npm run build:editor\` and commit the result`)
    process.exit(1)
  }
  console.log(`${output} matches its source`)
} else {
  await build({ ...options, outfile: output })
  const { size } = await stat(output)
  console.log(`wrote ${output} (${(size / 1024).toFixed(0)} KiB)`)
}
